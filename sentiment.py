LABEL_CN = {'positive': '正面', 'negative': '负面', 'neutral': '中性'}
LABEL_ORDER = ['positive', 'neutral', 'negative']


def analyze(text):
    """返回 {'pos':int,'neg':int,'polarity':float,'label':str,
             'pos_words':list,'neg_words':list}。"""
    text = text or ''
    pos_words = [w for w in POSITIVE if w in text]
    neg_words = [w for w in NEGATIVE if w in text]
    pos, neg = len(pos_words), len(neg_words)
    tot = pos + neg
    polarity = (pos - neg) / tot if tot else 0.0
    if polarity >= 0.2:
        label = 'positive'
    elif polarity <= -0.2:
        label = 'negative'
    else:
        label = 'neutral'
    return {
        'pos': pos, 'neg': neg, 'polarity': round(polarity, 3),
        'label': label, 'pos_words': pos_words, 'neg_words': neg_words,
    }


def label_of(text):
    return analyze(text)['label']
